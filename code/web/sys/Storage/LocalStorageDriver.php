<?php

require_once ROOT_DIR . '/sys/Storage/StorageDriver.php';

class LocalStorageDriver implements StorageDriver {

	// Served directly by Apache from the docroot on every deployment type; see StorageDriverFactory::resolvePublicRoot().
	private const PUBLIC_KEY_PREFIXES = ['files/', 'images/', 'fonts/'];
	private const DIRECTORY_MODE = 0775;

	// Registry files live under the public files/ folder so Apache serves them without going through PHP.
	private const REGISTRY_FOLDER = 'files/storage';

	private string $dataRoot;
	private string $publicRoot;
	private ?string $groupOwner;

	public function __construct(string $dataRoot, string $publicRoot, ?string $groupOwner = null) {
		$this->dataRoot = rtrim($dataRoot, '/');
		$this->publicRoot = rtrim($publicRoot, '/');
		$this->groupOwner = $groupOwner;
	}

	/**
	 * Registry keys are random ids generated by StorageObject::newKey(), e.g. 3f1a9c0e7b2d4a619f3e2a1b5c7d8e90.png.
	 * The folder they live in is derived from the id, so the database never stores a path.
	 */
	public static function isRegistryKey(string $key): bool {
		return preg_match('/^[0-9a-f]{32}(\.[a-z0-9]{1,8})?$/', $key) === 1;
	}

	/**
	 * Legacy keys point at a file written before the registry existed, either relative to the
	 * data or public root (same prefix rules as plain keys) or, if outside both, absolute.
	 */
	public static function isLegacyKey(string $key): bool {
		return str_starts_with($key, StorageDriver::LEGACY_KEY_PREFIX);
	}

	public static function isPublicKey(string $key): bool {
		foreach (self::PUBLIC_KEY_PREFIXES as $prefix) {
			if (str_starts_with($key, $prefix)) {
				return true;
			}
		}
		return false;
	}

	private function registryPath(string $key): string {
		return self::REGISTRY_FOLDER . '/' . substr($key, 0, 2) . '/' . substr($key, 2, 2) . '/' . $key;
	}

	/**
	 * Turns any key into a path relative to the public or data root, or an absolute path for
	 * legacy files that live outside both roots.
	 */
	private function relativePath(string $key): string {
		if (self::isRegistryKey($key)) {
			return $this->registryPath($key);
		}
		if (self::isLegacyKey($key)) {
			return substr($key, strlen(StorageDriver::LEGACY_KEY_PREFIX));
		}
		if (str_contains($key, '..')) {
			throw new InvalidArgumentException("Invalid storage key $key");
		}
		return ltrim($key, '/');
	}

	private function fullPath(string $key): string {
		$relativePath = $this->relativePath($key);
		if (str_starts_with($relativePath, '/')) {
			return $relativePath;
		}
		$root = self::isPublicKey($relativePath) ? $this->publicRoot : $this->dataRoot;
		return $root . '/' . $relativePath;
	}

	public function url(string $key, array $transforms = []): string {
		$relativePath = $this->relativePath($key);
		return self::isPublicKey($relativePath) ? '/' . $relativePath : '';
	}

	public function read(string $key): string|false {
		$path = $this->fullPath($key);
		if (!file_exists($path)) {
			return false;
		}
		return file_get_contents($path);
	}

	public function readStream(string $key) {
		$path = $this->fullPath($key);
		if (!file_exists($path)) {
			return false;
		}
		return fopen($path, 'rb');
	}

	public function write(string $key, string $tmpPath, string $mimeType = ''): bool {
		$dest = $this->fullPath($key);
		$dir = dirname($dest);
		if (!file_exists($dir)) {
			global $logger;
			// Collect every missing level so intermediate directories get the same group and mode
			$newDirs = [];
			for ($missing = $dir; !file_exists($missing); $missing = dirname($missing)) {
				$newDirs[] = $missing;
			}
			mkdir($dir, self::DIRECTORY_MODE, true);
			// A failure here doesn't block the write, but leaves the directory unusable by the other user
			foreach ($newDirs as $newDir) {
				if ($this->groupOwner !== null && !@chgrp($newDir, $this->groupOwner)) {
					$logger->log("Could not set group {$this->groupOwner} on $newDir", Logger::LOG_ERROR);
				}
				if (!@chmod($newDir, self::DIRECTORY_MODE)) {
					$logger->log("Could not set mode on $newDir", Logger::LOG_ERROR);
				}
			}
		}
		return copy($tmpPath, $dest);
	}

	public function delete(string $key): bool {
		$path = $this->fullPath($key);
		if (!file_exists($path)) {
			return false;
		}
		return unlink($path);
	}

	public function exists(string $key): bool {
		return file_exists($this->fullPath($key));
	}

	public function size(string $key): int|false {
		$path = $this->fullPath($key);
		if (!file_exists($path)) {
			return false;
		}
		return filesize($path);
	}
}
